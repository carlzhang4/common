package common.storage
import chisel3._
import chisel3.util._
import chisel3.experimental.{DataMirror, Direction, requireIsChiselType}
import common.axi._
import common.VivadoMarkDontTouch

object AXIRegSlice{
	def apply(stage: Int)(upStream: AXI) = {
		val downStream = Wire(chiselTypeOf(upStream))

		val regSlice = Seq.fill(stage)(Module(new AXIRegSlice(
			upStream.ar.bits.addr.getWidth,
			upStream.r.bits.data.getWidth, 
			upStream.ar.bits.id.getWidth, 
			upStream.ar.bits.user.getWidth, 
			upStream.ar.bits.len.getWidth
		)))

		regSlice(0).io.upStream			<> upStream
		regSlice(stage-1).io.downStream	<> downStream

		var i = 0
		for (i <- 0 until stage-1) {
			regSlice(i).io.downStream   <> regSlice(i+1).io.upStream
		}

		downStream
	}

	def apply(upStream: AXI) = {
		val downStream = Wire(chiselTypeOf(upStream))

		val regSlice = Module(new AXIRegSlice(
			upStream.ar.bits.addr.getWidth,
			upStream.r.bits.data.getWidth, 
			upStream.ar.bits.id.getWidth, 
			upStream.ar.bits.user.getWidth, 
			upStream.ar.bits.len.getWidth
		))

		regSlice.io.upStream    <> upStream
		regSlice.io.downStream  <> downStream

		downStream
	}
	
	class AXIRegSlice(ADDR_WIDTH:Int, DATA_WIDTH:Int, ID_WIDTH:Int, USER_WIDTH:Int, LEN_WIDTH:Int) extends Module() {
		val io = IO(new Bundle{
			val upStream = Flipped(new AXI(ADDR_WIDTH, DATA_WIDTH, ID_WIDTH, USER_WIDTH, LEN_WIDTH))
			val downStream = new AXI(ADDR_WIDTH, DATA_WIDTH, ID_WIDTH, USER_WIDTH, LEN_WIDTH)
		})

		io.downStream.aw	<> RegSlice(io.upStream.aw)
		io.downStream.ar	<> RegSlice(io.upStream.ar)
		io.downStream.w		<> RegSlice(io.upStream.w)
		io.upStream.r		<> RegSlice(io.downStream.r)
		io.upStream.b		<> RegSlice(io.downStream.b)
	}
}


// Timing-Optimized RegSlice is generated by GPT-6 Astra, based on Mo Sun's code.

object RegSlice{
	// bankWidth is the maximum packed payload bits per bank.
	// Existing calls automatically bank payloads wider than 128 bits.
	def apply[T<:Data](upStream: DecoupledIO[T], bankWidth: Int = 128) = {
		val downStream = Wire(chiselTypeOf(upStream))
		val queue = Module(new RegSlice(chiselTypeOf(upStream.bits), bankWidth))
		queue.io.upStream	<> upStream
		queue.io.downStream	<> downStream

		downStream
	}

	def apply[T<:Data](stage: Int)(upStream: DecoupledIO[T]): DecoupledIO[T] =
		apply(stage, 128)(upStream)

	def apply[T<:Data](stage: Int, bankWidth: Int)(upStream: DecoupledIO[T]): DecoupledIO[T] = {
		require(stage >= 1, "RegSlice stage must be positive")
		val downStream = Wire(chiselTypeOf(upStream))
		val queue = Seq.fill(stage)(Module(new RegSlice(chiselTypeOf(upStream.bits), bankWidth)))
		queue(0).io.upStream			<> upStream
		queue(stage-1).io.downStream	<> downStream

		var i = 0
		for (i <- 0 until stage-1) {
			queue(i).io.downStream	<> queue(i+1).io.upStream
		}

		downStream
	}
}

class RegSlice[T<:Data](gen : T, val bankWidth: Int = 64) extends Module{
	require(bankWidth >= 1, "RegSlice bankWidth must be positive")

	val genType = if (compileOptions.declaredTypeMustBeUnbound) {
		requireIsChiselType(gen)
		gen
	} else {
		if (DataMirror.internal.isSynthesizable(gen)) {
			chiselTypeOf(gen)
		} else {
			gen
		}
	}
	var io = IO(new Bundle {
		var upStream = Flipped(DecoupledIO(genType))
		var downStream = DecoupledIO(genType)
	})

	// Explicit Int.MaxValue opts out, including for widths inferred later.
	val numBanks = if (bankWidth == Int.MaxValue) 1 else {
		val width = io.upStream.bits.getWidth
		require(width > 0, "Banked RegSlice requires a known, positive payload width")
		1 + (width - 1) / bankWidth
	}

	if (numBanks == 1) {
		// Use the implementation of Analog Devices, Inc.

		val bwd_data_s 	= Wire(genType)
		val bwd_valid_s = Wire(Bool())
		val bwd_ready_s = Wire(UInt(1.W))
		val fwd_data_s 	= Wire(genType)
		val fwd_valid_s = Wire(UInt(1.W))
		val fwd_ready_s = Wire(Bool())

		val fwd_valid 	= RegInit(Bool(), false.B)
		val fwd_data 	= Reg(genType)

		fwd_ready_s := ~fwd_valid | io.downStream.ready
		fwd_valid_s := fwd_valid
		fwd_data_s	:= fwd_data

		fwd_data	:= Mux(~fwd_valid | io.downStream.ready, bwd_data_s, fwd_data)

		fwd_valid	:= Mux(bwd_valid_s, 1.U, Mux(io.downStream.ready, 0.U, fwd_valid))

		val bwd_ready	= RegInit(Bool(), true.B)
		val bwd_data 	= Reg(genType)

		bwd_valid_s	:= ~bwd_ready | io.upStream.valid
		bwd_data_s	:= Mux(bwd_ready, io.upStream.bits, bwd_data)
		bwd_ready_s	:= bwd_ready

		bwd_data	:= Mux(bwd_ready, io.upStream.bits, bwd_data)

		bwd_ready	:= Mux(fwd_ready_s, 1.U, Mux(io.upStream.valid, 0.U, bwd_ready))

		io.downStream.bits	:= fwd_data_s
		io.downStream.valid	:= fwd_valid_s
		io.upStream.ready	:= bwd_ready_s
	} else {
		val width = io.upStream.bits.getWidth
		require(width > 0, "Banked RegSlice requires a known, positive payload width")
		val packedIn = io.upStream.bits.asUInt
		val bankData = (0 until numBanks).map { i =>
			// The last bank contains only the remaining payload bits.
			val lo = i * bankWidth
			val hi = (lo.toLong + bankWidth).min(width.toLong).toInt - 1
			val fwdValid = VivadoMarkDontTouch(
				RegInit(false.B).suggestName(s"bank_${i}_fwd_valid"))
			val bwdReady = VivadoMarkDontTouch(
				RegInit(true.B).suggestName(s"bank_${i}_bwd_ready"))
			val fwdData = Reg(UInt((hi - lo + 1).W)).suggestName(s"bank_${i}_fwd_data")
			val bwdData = Reg(UInt((hi - lo + 1).W)).suggestName(s"bank_${i}_bwd_data")

			val fwdReady = !fwdValid || io.downStream.ready
			val selectedValid = !bwdReady || io.upStream.valid
			val inputData = packedIn(hi, lo)
			when(fwdReady) { fwdData := Mux(bwdReady, inputData, bwdData) }
			fwdValid := selectedValid || (fwdValid && !io.downStream.ready)
			when(bwdReady) { bwdData := inputData }
			bwdReady := Mux(fwdReady, true.B,
				Mux(io.upStream.valid, false.B, bwdReady))

			// All banks receive identical control inputs and reset, so their
			// state stays identical. No bank may consume or stall independently.
			if (i == 0) {
				io.upStream.ready := bwdReady
				io.downStream.valid := fwdValid
			}
			fwdData
		}
		io.downStream.bits := Cat(bankData.reverse).asTypeOf(genType)
	}
}
